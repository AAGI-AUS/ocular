## Replace NaN/Inf generated by ratio indices at zero denominators with NA.
.finiteIndex <- function(r){
  terra::ifel(is.finite(r), r, NA)
}

## Stable, dependency-free content digest for cache keys. Serialising the
## payload (rather than deparsing it) keeps names, types, and nested lists in
## the fingerprint. Four modular rolling hashes avoid temporary files and do
## not require filesystem access.
.stableHash <- function(payload){
  bytes <- as.integer(serialize(payload, NULL, version = 2))
  modulus <- c(2147483629, 2147483587, 2147483579, 2147483563)
  multiplier <- c(257, 263, 269, 271)
  seed <- c(17, 29, 43, 61)
  pieces <- vapply(seq_along(modulus), function(i){
    h <- seed[[i]]
    for( b in bytes ) h <- (h * multiplier[[i]] + b + 1) %% modulus[[i]]
    sprintf("%08x", as.integer(h))
  }, character(1L))
  paste0(pieces, collapse = "")
}
