################################################################################
# Core: shared constants and low-level utilities
#
# Definitions shared across retrieval, fusion, caching, and segmentation.
# The default stage sequence is implemented by boundary_delineation().
#
# rs structure:
#   spec      list -- user-supplied query: point (lon/lat), dates, dims,
#                    index_name, max_cloud_cover, scl_classes
#   geom      list -- derived spatial: bbox, source, pixel_size_m,
#                    nr, nc, centre_rc
#   scenes    list -- per-date {date, bands, index, item_assets} for
#                    index_name; user-extractable
#   internals list -- internal detection data: feature_stack, feat_array,
#                    mu, detection_scenes (search_index material when
#                    different from index_name)
#   state     list -- matrix carriers: alive_mat, decided_mat
#   params    list -- full populated rs_params list; auto-applied by every
#                    pipeline stage. Stage call-site overrides (params arg,
#                    inline named args) apply for that call only and do not
#                    mutate rs$params.
#
# Pipeline-execution state (pre-cleanup pending flags) is carried as
# attr(rs, "pending"), kept off the visible structure.
#
# Class: "ocular". Tested via is_rs(x).
#
################################################################################

## Derive unsupported fusion indices from the actual fine/coarse lookup
## pair. A function (not a constant) avoids relying on file collation order.
.fusionUnsupportedIndices <- function(){
  ln <- tryCatch(names(landsat_index_list), error = function(e) character(0))
  mn <- tryCatch(names(mcd43a4_index_list), error = function(e) character(0))
  return(setdiff(ln, mn))
}
